import { createRequire } from 'node:module';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

/**
 * Copies pinned browser assets that must be served as standalone files into the Web
 * application's static directory.
 *
 * The right-to-left text plugin is loaded by the renderer as a classic script from a URL rather
 * than imported as a module, so it cannot be bundled. Copying it from the pinned dependency
 * keeps it same-origin: the browser never contacts a plugin CDN.
 */
const root = resolve(import.meta.dirname, '..');
const webRoot = join(root, 'apps', 'web');
const vendorDirectory = join(webRoot, 'public', 'vendor');

// The package's export map exposes only its module entry, so the distributable script is
// located relative to the resolved package root rather than by a deep specifier.
const requireFromWeb = createRequire(join(webRoot, 'package.json'));
const packageRoot = resolve(dirname(requireFromWeb.resolve('@mapbox/mapbox-gl-rtl-text')), '..');

const assets = [
  {
    from: join(packageRoot, 'dist', 'mapbox-gl-rtl-text.js'),
    to: join(vendorDirectory, 'mapbox-gl-rtl-text.js'),
  },
  {
    from: join(packageRoot, 'LICENSE.md'),
    to: join(vendorDirectory, 'mapbox-gl-rtl-text.LICENSE.md'),
  },
];

await mkdir(vendorDirectory, { recursive: true });
for (const asset of assets) {
  await copyFile(asset.from, asset.to);
}

const version = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8')).version;
await writeFile(
  join(vendorDirectory, 'README.md'),
  [
    '# Vendored browser assets',
    '',
    'Generated by `scripts/vendor-web-assets.mjs`; not tracked in Git.',
    '',
    `- \`mapbox-gl-rtl-text.js\` — right-to-left text shaping, version ${version}, copied from the`,
    '  pinned `@mapbox/mapbox-gl-rtl-text` dependency. Its licence is copied alongside it.',
    '',
  ].join('\n'),
);

process.stdout.write(`Vendored ${assets.length} browser assets into apps/web/public/vendor.\n`);
